# Sass one-line installer for Windows: irm .../install.ps1 | iex
#Requires -Version 5.1
$ErrorActionPreference = 'Stop'

$SassHome = if ($env:SASS_HOME) { $env:SASS_HOME } else { Join-Path $env:USERPROFILE '.sass' }
$SassDir = if ($env:SASS_DIR) { $env:SASS_DIR } else { Join-Path $env:USERPROFILE 'Sass' }
$SassRepo = if ($env:SASS_REPO) { $env:SASS_REPO } else { 'https://github.com/philippsyrov/Sass.git' }
$SassBranch = if ($env:SASS_BRANCH) { $env:SASS_BRANCH } else { 'main' }
$NodeVersion = if ($env:SASS_NODE_VERSION) { $env:SASS_NODE_VERSION } else { '22.12.0' }
$BinDir = if ($env:SASS_BIN_DIR) { $env:SASS_BIN_DIR } else { Join-Path $env:USERPROFILE '.sass\bin' }

function Say($msg) { Write-Host $msg }
function Warn($msg) { Write-Host "  ! $msg" -ForegroundColor Yellow }

function Test-Git {
  if (Get-Command git -ErrorAction SilentlyContinue) { return $true }
  Say 'Git is required. Install from https://git-scm.com/download/win then run this installer again.'
  return $false
}

function Get-SystemNodeMajor {
  if (-not (Get-Command node -ErrorAction SilentlyContinue)) { return 0 }
  $v = (node -p "process.versions.node.split('.')[0]" 2>$null)
  if ($v) { return [int]$v }
  return 0
}

function Install-PrivateNode {
  $arch = if ([Environment]::Is64BitOperatingSystem) { 'x64' } else { 'x86' }
  $name = "node-v$NodeVersion-win-$arch"
  $zip = "$name.zip"
  $base = "https://nodejs.org/dist/v$NodeVersion"
  $dest = Join-Path $SassHome "node\v$NodeVersion"
  $tmp = Join-Path $env:TEMP "sass-node-$NodeVersion"
  New-Item -ItemType Directory -Force -Path $tmp | Out-Null
  Say "Downloading Node $NodeVersion (private copy under $SassHome)…"
  Invoke-WebRequest -Uri "$base/$zip" -OutFile (Join-Path $tmp $zip)
  Invoke-WebRequest -Uri "$base/SHASUMS256.txt" -OutFile (Join-Path $tmp 'SHASUMS256.txt')
  $expected = (Select-String -Path (Join-Path $tmp 'SHASUMS256.txt') -Pattern " $($zip)$").Line.Split(' ')[0]
  $hash = (Get-FileHash (Join-Path $tmp $zip) -Algorithm SHA256).Hash.ToLower()
  if ($hash -ne $expected.ToLower()) {
    throw 'Node download failed SHA256 verification.'
  }
  if (Test-Path $dest) { Remove-Item -Recurse -Force $dest }
  Expand-Archive -Path (Join-Path $tmp $zip) -DestinationPath (Join-Path $SassHome 'node') -Force
  Rename-Item (Join-Path $SassHome "node\$name") $dest
  $script:UsePrivateNode = $true
  Say 'Node installed under ~/.sass/node (does not change system Node).'
}

function Ensure-Node {
  $script:UsePrivateNode = $false
  if ((Get-SystemNodeMajor) -ge 20) {
    Say "Using Node $(node -v) from PATH."
    return
  }
  $private = Join-Path $SassHome 'node\current\node.exe'
  if ((Test-Path $private) -and (Get-SystemNodeMajor) -ge 20) {
    $script:UsePrivateNode = $true
    return
  }
  try {
    Install-PrivateNode
  } catch {
    Say 'Trying winget for Node.js LTS…'
    if (Get-Command winget -ErrorAction SilentlyContinue) {
      winget install --id OpenJS.NodeJS.LTS --accept-package-agreements --accept-source-agreements --silent | Out-Null
      if ((Get-SystemNodeMajor) -ge 20) { return }
    }
    throw $_
  }
}

function Write-EnvFile {
  New-Item -ItemType Directory -Force -Path $SassHome | Out-Null
  $nodePath = Join-Path $SassHome 'node\current'
  if ($script:UsePrivateNode) {
    @"
# Generated by install.ps1
SASS_DIR=$($SassDir -replace '\\','\\')
SASS_USE_PRIVATE_NODE=1
"@ | Set-Content (Join-Path $SassHome 'env.ps1') -Encoding UTF8
    cmd /c "mklink /J `"$(Join-Path $SassHome 'node\current')`" `"$(Join-Path $SassHome "node\v$NodeVersion")`"" 2>$null | Out-Null
  } else {
    @"
# Generated by install.ps1
SASS_DIR=$($SassDir -replace '\\','\\')
"@ | Set-Content (Join-Path $SassHome 'env.ps1') -Encoding UTF8
  }
}

function Ensure-Repo {
  if (Test-Path (Join-Path $SassDir '.git')) {
    Say "Updating Sass in $SassDir …"
    git -C $SassDir pull --ff-only
    return
  }
  Say "Cloning Sass into $SassDir …"
  New-Item -ItemType Directory -Force -Path (Split-Path $SassDir) | Out-Null
  git clone --branch $SassBranch --depth 1 $SassRepo $SassDir 2>$null
  if ($LASTEXITCODE -ne 0) { git clone --depth 1 $SassRepo $SassDir }
}

function Install-Launcher {
  New-Item -ItemType Directory -Force -Path $BinDir | Out-Null
  $cmd = @"
@echo off
setlocal
set "SASS_HOME=$SassHome"
if exist "%SASS_HOME%\env.ps1" for /f "usebackq tokens=*" %%a in ("%SASS_HOME%\env.ps1") do set SASS_DIR=$SassDir
if "$($script:UsePrivateNode)"=="True" set "PATH=$SassHome\node\v$NodeVersion;%PATH%"
set "SASS_DIR=$SassDir"
cd /d "$SassDir"
if "%~1"=="" goto start
if "%~1"=="setup" goto setup
if "%~1"=="update" goto update
if "%~1"=="doctor" goto doctor
if "%~1"=="stop" goto stop
if "%~1"=="help" goto help
echo Unknown command: %~1
goto help
:start
if not exist .env (echo Run: sass setup & exit /b 1)
call npm run build 2>nul
npm start
goto end
:setup
call npm run setup
goto end
:update
git pull --ff-only
call npm install --no-audit --no-fund --loglevel=error
call npm run build
goto end
:doctor
call npm run build 2>nul
call npm run doctor
goto end
:stop
echo Press Ctrl+C in the terminal where Sass is running.
goto end
:help
echo sass — start ^| setup ^| update ^| doctor ^| stop ^| help
:end
"@
  Set-Content -Path (Join-Path $BinDir 'sass.cmd') -Value $cmd -Encoding ASCII
  $userPath = [Environment]::GetEnvironmentVariable('Path', 'User')
  if ($userPath -notlike "*$BinDir*") {
    [Environment]::SetEnvironmentVariable('Path', "$BinDir;$userPath", 'User')
    Say "Added $BinDir to your user PATH (open a new terminal)."
  }
}

function Run-NpmInstall {
  Push-Location $SassDir
  if ($script:UsePrivateNode) {
    $env:PATH = "$(Join-Path $SassHome "node\v$NodeVersion");$env:PATH"
  }
  Say 'Installing npm packages…'
  npm install --no-audit --no-fund --loglevel=error
  if ($LASTEXITCODE -ne 0) {
    Warn 'npm install failed. Retrying with full output…'
    npm install --no-audit --no-fund
    if ($LASTEXITCODE -ne 0) { throw 'npm install failed.' }
  }
  Pop-Location
}

function Run-Setup {
  if ($env:SASS_SKIP_SETUP -eq '1') {
    Say 'Skipping setup wizard (SASS_SKIP_SETUP=1).'
    return
  }
  Say 'Starting the setup wizard…'
  Push-Location $SassDir
  if ($script:UsePrivateNode) {
    $env:PATH = "$(Join-Path $SassHome "node\v$NodeVersion");$env:PATH"
  }
  npm run setup
  Pop-Location
}

Say ''
Say 'Sass installer (Windows)'
Say '────────────────────────'
if (-not (Test-Git)) { exit 1 }
Ensure-Node
Write-EnvFile
Ensure-Repo
Install-Launcher
Run-NpmInstall
Run-Setup
Say ''
Say 'Done. Open a new terminal, then: sass setup (if needed), sass'
