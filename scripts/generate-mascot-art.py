#!/usr/bin/env python3
"""Render Sass mascot PNG to truecolor + 256-color ANSI half-block art and mascotData.ts."""
from __future__ import annotations

import math
import re
from pathlib import Path

from PIL import Image, ImageEnhance

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "assets" / "sass-mascot.png"
OUT_DIR = ROOT / "assets" / "mascot"
TS_OUT = ROOT / "src" / "setup" / "mascotData.generated.ts"

WIDTHS = (22, 30, 45)
BG = (30, 30, 30)


def rgb_to_xterm256(r: int, g: int, b: int) -> int:
    if r == g == b:
        if r < 8:
            return 16
        if r > 248:
            return 231
        return 232 + round((r - 8) / 247 * 23)
    return (
        16
        + 36 * round(r / 255 * 5)
        + 6 * round(g / 255 * 5)
        + round(b / 255 * 5)
    )


def truecolor_cell(top: tuple[int, ...], bot: tuple[int, ...]) -> str:
    ta, ba = top[3] > 110, bot[3] > 110
    if not ta and not ba:
        return "\x1b[0m "
    if ta and ba:
        return (
            f"\x1b[38;2;{top[0]};{top[1]};{top[2]}m"
            f"\x1b[48;2;{bot[0]};{bot[1]};{bot[2]}m▀"
        )
    if ta:
        return f"\x1b[0m\x1b[38;2;{top[0]};{top[1]};{top[2]}m▀"
    return f"\x1b[0m\x1b[38;2;{bot[0]};{bot[1]};{bot[2]}m▄"


def color256_cell(top: tuple[int, ...], bot: tuple[int, ...]) -> str:
    ta, ba = top[3] > 110, bot[3] > 110
    if not ta and not ba:
        return "\x1b[0m "
    if ta and ba:
        fg = rgb_to_xterm256(top[0], top[1], top[2])
        bg = rgb_to_xterm256(bot[0], bot[1], bot[2])
        return f"\x1b[38;5;{fg}m\x1b[48;5;{bg}m▀"
    if ta:
        fg = rgb_to_xterm256(top[0], top[1], top[2])
        return f"\x1b[0m\x1b[38;5;{fg}m▀"
    fg = rgb_to_xterm256(bot[0], bot[1], bot[2])
    return f"\x1b[0m\x1b[38;5;{fg}m▄"


def render_lines(im: Image.Image, cell_fn) -> list[str]:
    w, h = im.size
    lines: list[str] = []
    for y in range(0, h, 2):
        line = ""
        for x in range(w):
            t = im.getpixel((x, y))
            b = im.getpixel((x, y + 1))
            line += cell_fn(t, b)
        lines.append(line + "\x1b[0m")
    return lines


def art_for_width(src: Image.Image, w: int) -> Image.Image:
    h = round(w * src.height / src.width)
    h += h % 2
    return src.resize((w, h), Image.LANCZOS)


def escape_ts(s: str) -> str:
    return s.replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${")


def main() -> None:
    if not SRC.is_file():
        raise SystemExit(f"Missing {SRC}")
    src = ImageEnhance.Color(Image.open(SRC).convert("RGBA")).enhance(1.15)
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    ts_parts: list[str] = [
        "/** Generated by scripts/generate-mascot-art.py — do not edit. */",
        "",
    ]

    for w in WIDTHS:
        im = art_for_width(src, w)
        tc = render_lines(im, truecolor_cell)
        c256 = render_lines(im, color256_cell)
        (OUT_DIR / f"sass-{w}.truecolor.ans").write_text("\n".join(tc) + "\n", encoding="utf-8")
        (OUT_DIR / f"sass-{w}.256.ans").write_text("\n".join(c256) + "\n", encoding="utf-8")
        ts_parts.append(f"export const MASCOT_{w}_TRUECOLOR: readonly string[] = [")
        for line in tc:
            ts_parts.append(f"  `{escape_ts(line)}`,")
        ts_parts.append("] as const;")
        ts_parts.append("")
        ts_parts.append(f"export const MASCOT_{w}_256: readonly string[] = [")
        for line in c256:
            ts_parts.append(f"  `{escape_ts(line)}`,")
        ts_parts.append("] as const;")
        ts_parts.append("")

    installer_ui = ROOT / "scripts" / "install-ui.sh"
    ui_source = installer_ui.read_text(encoding="utf-8")
    for kind in ("truecolor", "256"):
        marker_name = "SASS_ART_" + kind.upper()
        before, marker, rest = ui_source.partition("  cat <<'" + marker_name + "'\n")
        if not marker:
            raise SystemExit("Installer mascot marker is missing: " + marker_name)
        _, end_marker, after = rest.partition(marker_name + "\n")
        if not end_marker:
            raise SystemExit("Installer mascot end marker is missing: " + marker_name)
        source_art = (OUT_DIR / f"sass-45.{kind}.ans").read_text(encoding="utf-8")
        ui_source = before + marker + source_art + end_marker + after
    installer_ui.write_text(ui_source, encoding="utf-8")

    TS_OUT.write_text("\n".join(ts_parts) + "\n", encoding="utf-8")
    print(f"Wrote {OUT_DIR} and {TS_OUT}")


if __name__ == "__main__":
    main()
